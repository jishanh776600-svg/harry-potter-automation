    def search_candidates(self, query: MovieEventQuery) -> List[MovieEvent]:
        """
        Discovers candidate events that match broad character/subject or setting criteria,
        before detailed multi-attribute scoring and visual verification.
        """
        candidates: Set[str] = set()

        # Subject match filter
        if query.subject:
            sub_key = query.subject.lower()
            for indexed_sub, event_ids in self._subject_index.items():
                if sub_key in indexed_sub or indexed_sub in sub_key:
                    candidates.update(event_ids)

        # Action match filter
        if query.action:
            action_tokens = self._tokenize(query.action)
            for token in action_tokens:
                if token in self._action_index:
                    candidates.update(self._action_index[token])

        # Location filter
        if query.location:
            loc_tokens = self._tokenize(query.location)
            for token in loc_tokens:
                if token in self._location_index:
                    candidates.update(self._location_index[token])

        # Object filter
        if query.objects:
            for obj in query.objects:
                for token in self._tokenize(obj):
                    if token in self._object_index:
                        candidates.update(self._object_index[token])

        # If specific movie requested
        if query.movie_number and query.movie_number in self._movie_index:
            movie_events = self._movie_index[query.movie_number]
            candidates = candidates.intersection(movie_events) if candidates else set(movie_events)

        # Fallback to all events if candidate set is empty
        if not candidates:
            return list(self._events.values())

        return [self._events[eid] for eid in candidates if eid in self._events]
