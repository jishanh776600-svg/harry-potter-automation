INDEX_STORAGE_PATH = PROJECT_ROOT / "data" / "cache" / "movie_events_v2_index.json"


class MovieEventIndex:
    """
    Searchable index of structured observable movie events.
    Does not modify or redownload movie assets; uses existing scene/shot units.
    """

    def __init__(self, index_path: Optional[Path] = None):
        self.index_path = index_path or INDEX_STORAGE_PATH
        self._events: Dict[str, MovieEvent] = {}
        self._subject_index: Dict[str, Set[str]] = {}
        self._action_index: Dict[str, Set[str]] = {}
        self._location_index: Dict[str, Set[str]] = {}
        self._object_index: Dict[str, Set[str]] = {}
        self._movie_index: Dict[int, Set[str]] = {}
        
        self._initialize_canonical_events()

    def add_event(self, event: MovieEvent) -> None:
        """Adds a verified movie event to the in-memory and relational indexes."""
        self._events[event.event_id] = event

        # Index primary & secondary subjects
        subjects = [event.primary_subject.lower()] + [s.lower() for s in event.secondary_subjects]
        for s in subjects:
            self._subject_index.setdefault(s, set()).add(event.event_id)

        # Index action tokens
        action_tokens = self._tokenize(event.action)
        for token in action_tokens:
            self._action_index.setdefault(token, set()).add(event.event_id)

        # Index location tokens
        location_tokens = self._tokenize(event.location)
        for token in location_tokens:
            self._location_index.setdefault(token, set()).add(event.event_id)

        # Index visible objects
        for obj in event.visible_objects:
            for token in self._tokenize(obj):
                self._object_index.setdefault(token, set()).add(event.event_id)

        # Index movie number
        self._movie_index.setdefault(event.movie_number, set()).add(event.event_id)

    def get_event(self, event_id: str) -> Optional[MovieEvent]:
        """Retrieves an event by its unique ID."""
        return self._events.get(event_id)

    def list_all_events(self) -> List[MovieEvent]:
        """Returns all currently indexed events."""
        return list(self._events.values())

    def _tokenize(self, text: str) -> List[str]:
        """Extracts clean alphanumeric tokens for index mapping."""
        import re
        return [w.lower() for w in re.findall(r"[a-zA-Z]{3,}", text or "")]

